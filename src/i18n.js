class I18nManager {
  constructor() {
    this.currentLang = 'vi';
    this.listeners = [];
  }

  init() {
    this.currentLang = this.detectLanguage();
    document.documentElement.lang = this.currentLang;
    this.applyDOM();

    // Nếu người dùng chưa từng chọn thủ công, thử định vị IP bất đồng bộ
    if (!localStorage.getItem('rubik_lang')) {
      this.detectCountryByIP().then(ipLang => {
        if (ipLang && ipLang !== this.currentLang && !localStorage.getItem('rubik_lang')) {
          this.setLanguage(ipLang, false);
        }
      });
    }
  }

  detectLanguage() {
    // 1. Kiểm tra lựa chọn đã lưu trong localStorage
    const saved = localStorage.getItem('rubik_lang');
    if (saved && TRANSLATIONS[saved]) {
      return saved;
    }

    // 2. Kiểm tra cài đặt ngôn ngữ trình duyệt / thiết bị (0ms latency)
    const navLangs = navigator.languages || [navigator.language || ''];
    for (const l of navLangs) {
      if (!l) continue;
      const lower = l.toLowerCase();
      for (const item of SUPPORTED_LANGUAGES) {
        if (lower.startsWith(item.code)) return item.code;
      }
    }

    // Mặc định ban đầu
    return 'vi';
  }

  async detectCountryByIP() {
    try {
      const res = await fetch('https://ipapi.co/json/', { signal: AbortSignal.timeout(3000) });
      if (!res.ok) return null;
      const data = await res.json();
      const country = data.country_code || data.country;
      if (!country) return null;

      const c = country.toUpperCase();
      if (c === 'VN') return 'vi';
      if (c === 'JP') return 'ja';
      if (['CN', 'TW', 'HK', 'MO'].includes(c)) return 'zh';
      if (['ES', 'MX', 'AR', 'CO', 'CL', 'PE', 'VE', 'EC', 'GT', 'CU', 'BO', 'DO', 'HN', 'PY', 'SV', 'NI', 'CR', 'PA', 'UY', 'PR'].includes(c)) return 'es';
      if (['FR', 'BE', 'MC'].includes(c)) return 'fr';
      if (['DE', 'AT', 'CH'].includes(c)) return 'de';
      if (['RU', 'BY', 'KZ', 'KG'].includes(c)) return 'ru';
      if (['BR', 'PT', 'AO', 'MZ'].includes(c)) return 'pt';
      if (c === 'KR') return 'ko';
      if (c === 'IT') return 'it';
      if (['SA', 'AE', 'EG', 'IQ', 'DZ', 'MA', 'KW', 'QA'].includes(c)) return 'ar';
      if (c === 'IN') return 'hi';
      if (c === 'ID') return 'id';
      if (c === 'TR') return 'tr';
      return 'en';
    } catch {
      return null;
    }
  }

  setLanguage(langCode, saveToStorage = true) {
    if (!TRANSLATIONS[langCode]) return;
    this.currentLang = langCode;
    if (saveToStorage && typeof localStorage !== 'undefined') {
      localStorage.setItem('rubik_lang', langCode);
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = langCode;
      this.applyDOM();
    }
    this.emitChange();
  }

  t(key, params = {}) {
    const dict = TRANSLATIONS[this.currentLang];
    // Fallback: If current language is not Vietnamese, fallback to English first to prevent Vietnamese leaking!
    let str = (dict && dict[key]) || (this.currentLang !== 'vi' ? TRANSLATIONS.en[key] : null) || TRANSLATIONS.vi[key] || key;
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return str;
  }

  getLanguage() {
    return this.currentLang;
  }

  getLanguageMeta() {
    return SUPPORTED_LANGUAGES.find(l => l.code === this.currentLang) || SUPPORTED_LANGUAGES[0];
  }

  applyDOM() {
    document.title = this.t('app_title');

    // Cập nhật text cho các thẻ có data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = this.t(key);
      }
    });

    // Cập nhật title tooltip cho các thẻ có data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (key) {
        el.title = this.t(key);
      }
    });

    // Cập nhật HTML cho các thẻ có data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (key) {
        el.innerHTML = this.t(key);
      }
    });

    // Tự động đồng bộ data-view-label cho 2D Viewports
    document.querySelectorAll('[data-view-label-key]').forEach(el => {
      const key = el.getAttribute('data-view-label-key');
      const prefix = el.getAttribute('data-view-label-prefix') || '';
      if (key) {
        el.setAttribute('data-view-label', prefix + this.t(key));
      }
    });
  }

  onChange(callback) {
    this.listeners.push(callback);
  }

  emitChange() {
    for (const cb of this.listeners) {
      try {
        cb(this.currentLang);
      } catch (e) {
        console.error('Error in i18n change listener:', e);
      }
    }
  }
}

export const i18n = new I18nManager();
